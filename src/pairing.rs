const DOMAIN_PAIR_SAS: &[u8] = b"sshcast-pair-sas-v1\x00";
const DOMAIN_PAIR_SIG: &[u8] = b"sshcast-pair-sig-v1\x00";
const DOMAIN_PAIR_HANDOFF: &[u8] = b"sshcast-pair-handoff-v1\x00";
const DOMAIN_PAIR_AAD: &[u8] = b"sshcast-pair-aad-v1\x00";
const DOMAIN_RECOVERY_VAULT_AAD: &[u8] = b"sshcast-recovery-vault-v1\x00";

const USER_PUBKEY_TOKEN_PREFIX: &str = "sc_pub_";
const AEAD_TAG_LEN: usize = 16;
const AEAD_NONCE_LEN: usize = 12;
const MAX_SCRYPT_MEMORY_BYTES: usize = 256 * 1024 * 1024;
const MAX_VAULT_CIPHERTEXT_BYTES: usize = 4096;

/// Parses a `sc_pub_<64 hex>` user public key token into its raw 32-byte Ed25519 public key.
pub fn parse_user_pubkey_token(token: &str) -> Result<[u8; 32]> {
    let trimmed = token.trim();
    let hex_part = trimmed
        .strip_prefix(USER_PUBKEY_TOKEN_PREFIX)
        .ok_or_else(|| anyhow!("user pubkey token must start with '{USER_PUBKEY_TOKEN_PREFIX}'"))?;
    let bytes = hex::decode(hex_part.trim()).context("invalid hex in sc_pub_ user pubkey token")?;
    let key: [u8; 32] = bytes
        .try_into()
        .map_err(|_| anyhow!("sc_pub_ user pubkey token must decode to 32 bytes"))?;
    Ok(key)
}

/// Computes the 6-digit (`XXX-XXX`) Short Authentication String (SAS) displayed on both
/// workstations so the user can verify the requester's ephemeral X25519 key out-of-band.
pub fn compute_pairing_sas_code(
    existing_user_pubkey: &[u8; 32],
    requester_eph_x25519_pub: &[u8; 32],
) -> String {
    let mut hasher = Sha256::new();
    hasher.update(DOMAIN_PAIR_SAS);
    hasher.update(existing_user_pubkey);
    hasher.update(requester_eph_x25519_pub);
    let digest = hasher.finalize();
    let val = u32::from_be_bytes([digest[0], digest[1], digest[2], digest[3]]);
    let num = val % 1_000_000;
    format!("{:03}-{:03}", num / 1000, num % 1000)
}

/// Plaintext payload sealed inside `PairingHandoffEnvelope.encrypted_handoff_b64`.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PairingHandoffPayload {
    pub version: u32,
    pub grant_proto_b64: String,
    pub user_privkey_seed_b64: String,
    pub servers: Vec<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub operator_url: Option<String>,
}

/// Signed and AEAD-encrypted pairing response transmitted via the operator server.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PairingHandoffEnvelope {
    pub approver_eph_x25519_pub_b64: String,
    pub approver_signature_b64: String,
    pub handoff_nonce_b64: String,
    pub encrypted_handoff_b64: String,
}

/// Verified and decrypted workstation enrollment material produced on Workstation B.
#[derive(Debug, Clone)]
pub struct VerifiedPairingHandoff {
    pub grant: NodeGrant,
    pub user_signing_key: SigningKey,
    pub node_signing_key: SigningKey,
    pub servers: Vec<String>,
    pub operator_url: Option<String>,
}

/// Ephemeral X25519 keypair and fresh node Ed25519 identity generated by the requesting workstation.
#[derive(Debug)]
pub struct RequesterPairingKeys {
    node_signing_key: SigningKey,
    eph_private: EphemeralPrivateKey,
    eph_public_bytes: [u8; 32],
}

impl RequesterPairingKeys {
    /// Generates a fresh Ed25519 node signing key and an ephemeral X25519 pairing keypair.
    pub fn generate() -> Result<Self> {
        let node_signing_key = SigningKey::generate(&mut OsRng);
        let rng = SystemRandom::new();
        let eph_private = EphemeralPrivateKey::generate(&X25519, &rng)
            .map_err(|_| anyhow!("failed to generate ephemeral X25519 keypair"))?;
        let eph_public = eph_private
            .compute_public_key()
            .map_err(|_| anyhow!("failed to compute ephemeral X25519 public key"))?;
        let eph_public_bytes: [u8; 32] = eph_public
            .as_ref()
            .try_into()
            .map_err(|_| anyhow!("unexpected X25519 public key length"))?;
        Ok(Self {
            node_signing_key,
            eph_private,
            eph_public_bytes,
        })
    }

    /// Returns the newly generated workstation node signing key.
    pub fn node_signing_key(&self) -> &SigningKey {
        &self.node_signing_key
    }

    /// Returns the raw 32-byte ephemeral X25519 public key.
    pub fn eph_public_bytes(&self) -> &[u8; 32] {
        &self.eph_public_bytes
    }

    /// Returns the standard base64-encoded 32-byte Ed25519 node public key.
    pub fn node_pubkey_b64(&self) -> String {
        STANDARD.encode(self.node_signing_key.verifying_key().to_bytes())
    }

    /// Returns the standard base64-encoded 32-byte ephemeral X25519 public key.
    pub fn eph_x25519_pub_b64(&self) -> String {
        STANDARD.encode(self.eph_public_bytes)
    }

    /// Computes the 6-digit (`XXX-XXX`) SAS verification code for this pairing session.
    pub fn sas_code(&self, existing_user_pubkey: &[u8; 32]) -> String {
        compute_pairing_sas_code(existing_user_pubkey, &self.eph_public_bytes)
    }

    /// Verifies the approver's Ed25519 transcript signature, derives the X25519+HKDF key,
    /// decrypts the pairing handoff envelope, and validates the inner root key and `NodeGrant`.
    pub fn decrypt_and_verify_handoff(
        self,
        pairing_id: &str,
        existing_user_pubkey: &[u8; 32],
        envelope: &PairingHandoffEnvelope,
    ) -> Result<VerifiedPairingHandoff> {
        if pairing_id.is_empty() {
            bail!("pairing_id cannot be empty");
        }

        let eph_pub_a: [u8; 32] = decode_base64_fixed(
            &envelope.approver_eph_x25519_pub_b64,
            "approver_eph_x25519_pub_b64",
        )?;
        let approver_sig_bytes: [u8; 64] =
            decode_base64_fixed(&envelope.approver_signature_b64, "approver_signature_b64")?;
        let nonce_bytes: [u8; AEAD_NONCE_LEN] =
            decode_base64_fixed(&envelope.handoff_nonce_b64, "handoff_nonce_b64")?;
        let ciphertext = decode_base64_flexible(&envelope.encrypted_handoff_b64)
            .context("invalid base64 in encrypted_handoff_b64")?;
        if ciphertext.len() < AEAD_TAG_LEN {
            bail!("encrypted_handoff_b64 is shorter than ChaCha20-Poly1305 tag");
        }

        let user_vk = VerifyingKey::from_bytes(existing_user_pubkey)
            .context("invalid existing_user_pubkey Ed25519 key")?;
        let approver_sig = Signature::from_bytes(&approver_sig_bytes);
        let sig_msg = pairing_signature_message(
            pairing_id,
            &eph_pub_a,
            &self.eph_public_bytes,
            &nonce_bytes,
            &ciphertext,
        );
        user_vk
            .verify(&sig_msg, &approver_sig)
            .context("approver Ed25519 signature verification failed on pairing handoff")?;

        let aead_key = derive_pairing_aead_key(
            self.eph_private,
            &eph_pub_a,
            existing_user_pubkey,
            pairing_id,
            &eph_pub_a,
            &self.eph_public_bytes,
        )?;
        let aad = pairing_aad(
            pairing_id,
            existing_user_pubkey,
            &eph_pub_a,
            &self.eph_public_bytes,
        );

        let mut buf = Zeroizing::new(ciphertext);
        let plaintext = aead_key
            .open_in_place(
                Nonce::assume_unique_for_key(nonce_bytes),
                Aad::from(aad.as_slice()),
                buf.as_mut_slice(),
            )
            .map_err(|_| anyhow!("pairing handoff AEAD decryption failed"))?;

        let mut payload: PairingHandoffPayload =
            serde_json::from_slice(plaintext).context("failed to parse PairingHandoffPayload")?;
        buf.zeroize();

        if payload.version != 1 {
            payload.user_privkey_seed_b64.zeroize();
            bail!("unsupported PairingHandoffPayload version {}", payload.version);
        }

        let user_seed = decode_seed_32(&payload.user_privkey_seed_b64, "user_privkey_seed_b64");
        payload.user_privkey_seed_b64.zeroize();
        let user_seed = user_seed?;
        let user_signing_key = SigningKey::from_bytes(&user_seed);
        if user_signing_key.verifying_key().to_bytes() != *existing_user_pubkey {
            bail!("decrypted user_privkey_seed_b64 does not match existing_user_pubkey");
        }

        let grant_bytes = URL_SAFE_NO_PAD
            .decode(payload.grant_proto_b64.trim())
            .context("invalid URL-safe base64 in grant_proto_b64")?;
        let grant = NodeGrant::decode(grant_bytes.as_slice())
            .context("failed to decode NodeGrant protobuf in pairing handoff")?;

        let now_sec = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap_or_default()
            .as_secs();
        verify_node_grant(&grant, now_sec)
            .context("pairing handoff NodeGrant verification failed")?;

        if grant.role != NodeRole::Client as i32 {
            bail!("pairing handoff NodeGrant role must be CLIENT (got {})", grant.role);
        }
        if grant.user_pubkey.as_slice() != existing_user_pubkey.as_slice() {
            bail!("pairing handoff NodeGrant user_pubkey does not match existing_user_pubkey");
        }
        let expected_node_pub = self.node_signing_key.verifying_key().to_bytes();
        if grant.node_pubkey.as_slice() != expected_node_pub.as_slice() {
            bail!("pairing handoff NodeGrant node_pubkey does not match requester node key");
        }

        Ok(VerifiedPairingHandoff {
            grant,
            user_signing_key,
            node_signing_key: self.node_signing_key,
            servers: payload.servers,
            operator_url: payload.operator_url,
        })
    }
}

/// Approver-side helper that mints a client `NodeGrant`, seals the user root key and config into
/// an E2E-encrypted `PairingHandoffEnvelope`, and signs the handoff transcript with `user_sk`.
#[allow(clippy::too_many_arguments)]
pub fn create_encrypted_pairing_handoff(
    user_sk: &SigningKey,
    user_cert: Option<UserCert>,
    pairing_id: &str,
    requester_node_name: &str,
    requester_node_pubkey: &[u8; 32],
    requester_eph_x25519_pub: &[u8; 32],
    servers: Vec<String>,
    operator_url: Option<String>,
) -> Result<PairingHandoffEnvelope> {
    if pairing_id.is_empty() {
        bail!("pairing_id cannot be empty");
    }
    let node_id = requester_node_name.trim();
    if node_id.is_empty() {
        bail!("requester_node_name cannot be empty");
    }
    VerifyingKey::from_bytes(requester_node_pubkey)
        .context("invalid requester_node_pubkey Ed25519 key")?;

    let user_pubkey = user_sk.verifying_key().to_bytes();
    let verified_cert = user_cert.filter(|c| c.user_pubkey.as_slice() == user_pubkey.as_slice());
    let now_sec = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_secs();

    let mut grant = NodeGrant {
        user_id: String::new(),
        user_pubkey: Vec::new(),
        node_id: node_id.to_string(),
        role: NodeRole::Client as i32,
        node_pubkey: requester_node_pubkey.to_vec(),
        issued_at_unix_sec: now_sec,
        expires_at_unix_sec: 0,
        user_signature: Vec::new(),
        user_cert: verified_cert,
    };
    sign_node_grant(&mut grant, user_sk);

    let mut grant_bytes = Vec::new();
    grant
        .encode(&mut grant_bytes)
        .expect("prost encode cannot fail on Vec");

    let user_seed = Zeroizing::new(user_sk.to_bytes());
    let mut payload = PairingHandoffPayload {
        version: 1,
        grant_proto_b64: URL_SAFE_NO_PAD.encode(&grant_bytes),
        user_privkey_seed_b64: URL_SAFE_NO_PAD.encode(&*user_seed),
        servers,
        operator_url,
    };

    let mut payload_bytes = Zeroizing::new(
        serde_json::to_vec(&payload).context("failed to serialize PairingHandoffPayload")?,
    );
    payload.user_privkey_seed_b64.zeroize();
    drop(payload);

    let rng = SystemRandom::new();
    let eph_private = EphemeralPrivateKey::generate(&X25519, &rng)
        .map_err(|_| anyhow!("failed to generate approver ephemeral X25519 keypair"))?;
    let eph_public = eph_private
        .compute_public_key()
        .map_err(|_| anyhow!("failed to compute approver ephemeral X25519 public key"))?;
    let eph_pub_a: [u8; 32] = eph_public
        .as_ref()
        .try_into()
        .map_err(|_| anyhow!("unexpected X25519 public key length"))?;

    let mut nonce_bytes = [0u8; AEAD_NONCE_LEN];
    rng.fill(&mut nonce_bytes)
        .map_err(|_| anyhow!("failed to generate random handoff nonce"))?;

    let aead_key = derive_pairing_aead_key(
        eph_private,
        requester_eph_x25519_pub,
        &user_pubkey,
        pairing_id,
        &eph_pub_a,
        requester_eph_x25519_pub,
    )?;
    let aad = pairing_aad(
        pairing_id,
        &user_pubkey,
        &eph_pub_a,
        requester_eph_x25519_pub,
    );

    let mut seal_buf = Zeroizing::new(Vec::with_capacity(payload_bytes.len() + AEAD_TAG_LEN));
    seal_buf.extend_from_slice(&payload_bytes);
    payload_bytes.zeroize();

    aead_key
        .seal_in_place_append_tag(
            Nonce::assume_unique_for_key(nonce_bytes),
            Aad::from(aad.as_slice()),
            &mut *seal_buf,
        )
        .map_err(|_| anyhow!("pairing handoff AEAD encryption failed"))?;

    let sig_msg = pairing_signature_message(
        pairing_id,
        &eph_pub_a,
        requester_eph_x25519_pub,
        &nonce_bytes,
        &seal_buf,
    );
    let approver_sig = user_sk.sign(&sig_msg);

    Ok(PairingHandoffEnvelope {
        approver_eph_x25519_pub_b64: STANDARD.encode(eph_pub_a),
        approver_signature_b64: STANDARD.encode(approver_sig.to_bytes()),
        handoff_nonce_b64: STANDARD.encode(nonce_bytes),
        encrypted_handoff_b64: STANDARD.encode(&*seal_buf),
    })
}

fn derive_pairing_aead_key(
    eph_private: EphemeralPrivateKey,
    peer_eph_pub: &[u8; 32],
    existing_user_pubkey: &[u8; 32],
    pairing_id: &str,
    eph_pub_a: &[u8; 32],
    eph_pub_b: &[u8; 32],
) -> Result<LessSafeKey> {
    let peer = UnparsedPublicKey::new(&X25519, peer_eph_pub);
    let info = [
        DOMAIN_PAIR_HANDOFF,
        pairing_id.as_bytes(),
        eph_pub_a.as_slice(),
        eph_pub_b.as_slice(),
    ];
    let key = agree_ephemeral(eph_private, &peer, |shared| {
        let prk = Salt::new(HKDF_SHA256, existing_user_pubkey).extract(shared);
        let okm = prk
            .expand(&info, &CHACHA20_POLY1305)
            .map_err(|_| anyhow!("HKDF expansion failed for pairing handoff"))?;
        Ok::<_, anyhow::Error>(LessSafeKey::new(UnboundKey::from(okm)))
    })
    .map_err(|_| anyhow!("X25519 key agreement failed (invalid peer ephemeral key)"))??;
    Ok(key)
}

fn pairing_signature_message(
    pairing_id: &str,
    eph_pub_a: &[u8; 32],
    eph_pub_b: &[u8; 32],
    nonce: &[u8; AEAD_NONCE_LEN],
    ciphertext: &[u8],
) -> Vec<u8> {
    let ct_hash = Sha256::digest(ciphertext);
    let mut msg = Vec::with_capacity(
        DOMAIN_PAIR_SIG.len() + pairing_id.len() + 32 + 32 + AEAD_NONCE_LEN + 32,
    );
    msg.extend_from_slice(DOMAIN_PAIR_SIG);
    msg.extend_from_slice(pairing_id.as_bytes());
    msg.extend_from_slice(eph_pub_a);
    msg.extend_from_slice(eph_pub_b);
    msg.extend_from_slice(nonce);
    msg.extend_from_slice(&ct_hash);
    msg
}

fn pairing_aad(
    pairing_id: &str,
    existing_user_pubkey: &[u8; 32],
    eph_pub_a: &[u8; 32],
    eph_pub_b: &[u8; 32],
) -> Vec<u8> {
    let mut aad = Vec::with_capacity(DOMAIN_PAIR_AAD.len() + pairing_id.len() + 32 + 32 + 32);
    aad.extend_from_slice(DOMAIN_PAIR_AAD);
    aad.extend_from_slice(pairing_id.as_bytes());
    aad.extend_from_slice(existing_user_pubkey);
    aad.extend_from_slice(eph_pub_a);
    aad.extend_from_slice(eph_pub_b);
    aad
}

/// Parameters controlling RFC 7914 `scrypt` memory and CPU cost.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct ScryptParams {
    pub log_n: u8,
    pub r: u32,
    pub p: u32,
}

impl Default for ScryptParams {
    fn default() -> Self {
        Self {
            log_n: 15,
            r: 8,
            p: 1,
        }
    }
}

/// Passphrase-encrypted user root key backup stored server-side on the operator.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RecoveryVaultBlob {
    pub version: u32,
    pub kdf_alg: String,
    pub kdf_params: ScryptParams,
    pub salt_b64: String,
    pub nonce_b64: String,
    pub ciphertext_b64: String,
}

/// Errors returned when decrypting or validating a [`RecoveryVaultBlob`].
#[derive(Debug, thiserror::Error)]
pub enum VaultDecryptError {
    #[error("incorrect recovery passphrase")]
    WrongPassphrase,
    #[error("invalid recovery vault: {0}")]
    InvalidFormat(String),
}

fn validate_scrypt_params(params: ScryptParams) -> std::result::Result<(usize, usize), String> {
    if !(1..=20).contains(&params.log_n) {
        return Err(format!("scrypt log_n {} out of allowed range 1..=20", params.log_n));
    }
    if !(1..=32).contains(&params.r) {
        return Err(format!("scrypt r {} out of allowed range 1..=32", params.r));
    }
    if !(1..=16).contains(&params.p) {
        return Err(format!("scrypt p {} out of allowed range 1..=16", params.p));
    }
    let n = 1usize
        .checked_shl(u32::from(params.log_n))
        .ok_or_else(|| "scrypt N overflow".to_string())?;
    let block_bytes = 128usize
        .checked_mul(params.r as usize)
        .ok_or_else(|| "scrypt block size overflow".to_string())?;
    let v_bytes = block_bytes
        .checked_mul(n)
        .ok_or_else(|| "scrypt memory size overflow".to_string())?;
    if v_bytes > MAX_SCRYPT_MEMORY_BYTES {
        return Err(format!(
            "scrypt memory requirement {v_bytes} bytes exceeds limit of {MAX_SCRYPT_MEMORY_BYTES} bytes"
        ));
    }
    Ok((n, block_bytes))
}

/// Derives `dk_len` bytes using RFC 7914 `scrypt` backed by `ring` PBKDF2-HMAC-SHA256.
pub fn scrypt_rfc7914(
    password: &[u8],
    salt: &[u8],
    log_n: u8,
    r: u32,
    p: u32,
    dk_len: usize,
) -> Result<Vec<u8>> {
    if dk_len == 0 {
        bail!("dk_len must be > 0");
    }
    let max_pbkdf2_len = u64::from(u32::MAX) * 32;
    if u64::try_from(dk_len).unwrap_or(u64::MAX) > max_pbkdf2_len {
        bail!("dk_len exceeds PBKDF2-HMAC-SHA256 maximum output length");
    }

    let params = ScryptParams { log_n, r, p };
    let (n, block_bytes) = validate_scrypt_params(params).map_err(|e| anyhow!(e))?;
    let b_bytes = block_bytes
        .checked_mul(p as usize)
        .ok_or_else(|| anyhow!("scrypt working buffer size overflow"))?;

    let one = NonZeroU32::new(1).expect("1 is non-zero");
    let mut b = Zeroizing::new(vec![0u8; b_bytes]);
    pbkdf2_derive(PBKDF2_HMAC_SHA256, one, salt, password, &mut b);

    let block_words = 32usize * (r as usize);
    let mut v = Zeroizing::new(vec![0u32; n * block_words]);
    let mut x = Zeroizing::new(vec![0u32; block_words]);
    let mut scratch = Zeroizing::new(vec![0u32; block_words]);

    for chunk in b.chunks_exact_mut(block_bytes) {
        for (dst, src) in x.iter_mut().zip(chunk.chunks_exact(4)) {
            *dst = u32::from_le_bytes([src[0], src[1], src[2], src[3]]);
        }
        scrypt_ro_mix(&mut x, &mut scratch, &mut v, r as usize, n);
        for (dst, src) in chunk.chunks_exact_mut(4).zip(x.iter()) {
            dst.copy_from_slice(&src.to_le_bytes());
        }
    }

    let mut dk = vec![0u8; dk_len];
    pbkdf2_derive(PBKDF2_HMAC_SHA256, one, &b, password, &mut dk);
    Ok(dk)
}

#[inline]
fn salsa20_8(b: &mut [u32; 16]) {
    let mut z = *b;
    for _ in 0..4 {
        // Column round
        z[4] ^= z[0].wrapping_add(z[12]).rotate_left(7);
        z[8] ^= z[4].wrapping_add(z[0]).rotate_left(9);
        z[12] ^= z[8].wrapping_add(z[4]).rotate_left(13);
        z[0] ^= z[12].wrapping_add(z[8]).rotate_left(18);

        z[9] ^= z[5].wrapping_add(z[1]).rotate_left(7);
        z[13] ^= z[9].wrapping_add(z[5]).rotate_left(9);
        z[1] ^= z[13].wrapping_add(z[9]).rotate_left(13);
        z[5] ^= z[1].wrapping_add(z[13]).rotate_left(18);

        z[14] ^= z[10].wrapping_add(z[6]).rotate_left(7);
        z[2] ^= z[14].wrapping_add(z[10]).rotate_left(9);
        z[6] ^= z[2].wrapping_add(z[14]).rotate_left(13);
        z[10] ^= z[6].wrapping_add(z[2]).rotate_left(18);

        z[3] ^= z[15].wrapping_add(z[11]).rotate_left(7);
        z[7] ^= z[3].wrapping_add(z[15]).rotate_left(9);
        z[11] ^= z[7].wrapping_add(z[3]).rotate_left(13);
        z[15] ^= z[11].wrapping_add(z[7]).rotate_left(18);

        // Row round
        z[1] ^= z[0].wrapping_add(z[3]).rotate_left(7);
        z[2] ^= z[1].wrapping_add(z[0]).rotate_left(9);
        z[3] ^= z[2].wrapping_add(z[1]).rotate_left(13);
        z[0] ^= z[3].wrapping_add(z[2]).rotate_left(18);

        z[6] ^= z[5].wrapping_add(z[4]).rotate_left(7);
        z[7] ^= z[6].wrapping_add(z[5]).rotate_left(9);
        z[4] ^= z[7].wrapping_add(z[6]).rotate_left(13);
        z[5] ^= z[4].wrapping_add(z[7]).rotate_left(18);

        z[11] ^= z[10].wrapping_add(z[9]).rotate_left(7);
        z[8] ^= z[11].wrapping_add(z[10]).rotate_left(9);
        z[9] ^= z[8].wrapping_add(z[11]).rotate_left(13);
        z[10] ^= z[9].wrapping_add(z[8]).rotate_left(18);

        z[12] ^= z[15].wrapping_add(z[14]).rotate_left(7);
        z[13] ^= z[12].wrapping_add(z[15]).rotate_left(9);
        z[14] ^= z[13].wrapping_add(z[12]).rotate_left(13);
        z[15] ^= z[14].wrapping_add(z[13]).rotate_left(18);
    }
    for (dst, src) in b.iter_mut().zip(z.iter()) {
        *dst = dst.wrapping_add(*src);
    }
    z.zeroize();
}

fn scrypt_block_mix(input: &[u32], output: &mut [u32], r: usize) {
    let mut x = [0u32; 16];
    let last_offset = (2 * r - 1) * 16;
    x.copy_from_slice(&input[last_offset..last_offset + 16]);

    for i in 0..(2 * r) {
        let in_off = i * 16;
        for j in 0..16 {
            x[j] ^= input[in_off + j];
        }
        salsa20_8(&mut x);
        let dst_block = if i % 2 == 0 { i / 2 } else { r + (i / 2) };
        let out_off = dst_block * 16;
        output[out_off..out_off + 16].copy_from_slice(&x);
    }
    x.zeroize();
}

fn scrypt_ro_mix(x: &mut Vec<u32>, scratch: &mut Vec<u32>, v: &mut [u32], r: usize, n: usize) {
    let block_words = 32 * r;
    let integerify_idx = (2 * r - 1) * 16;
    let n_mask = n - 1;

    for i in 0..n {
        let v_off = i * block_words;
        v[v_off..v_off + block_words].copy_from_slice(x);
        scrypt_block_mix(x, scratch, r);
        std::mem::swap(x, scratch);
    }

    for _ in 0..n {
        let j = (x[integerify_idx] as usize) & n_mask;
        let v_off = j * block_words;
        for (dst, src) in x.iter_mut().zip(&v[v_off..v_off + block_words]) {
            *dst ^= *src;
        }
        scrypt_block_mix(x, scratch, r);
        std::mem::swap(x, scratch);
    }
}

/// Encrypts `user_sk` under `passphrase` using RFC 7914 `scrypt` and ChaCha20-Poly1305.
pub fn encrypt_recovery_vault(
    user_sk: &SigningKey,
    passphrase: &str,
    params: ScryptParams,
) -> Result<RecoveryVaultBlob> {
    if passphrase.is_empty() {
        bail!("recovery passphrase cannot be empty");
    }
    validate_scrypt_params(params).map_err(|e| anyhow!(e))?;

    let rng = SystemRandom::new();
    let mut salt = [0u8; 16];
    rng.fill(&mut salt)
        .map_err(|_| anyhow!("failed to generate random salt for recovery vault"))?;
    let mut nonce_bytes = [0u8; AEAD_NONCE_LEN];
    rng.fill(&mut nonce_bytes)
        .map_err(|_| anyhow!("failed to generate random nonce for recovery vault"))?;

    let key = Zeroizing::new(scrypt_rfc7914(
        passphrase.as_bytes(),
        &salt,
        params.log_n,
        params.r,
        params.p,
        32,
    )?);

    let user_pubkey = user_sk.verifying_key().to_bytes();
    let aad = recovery_vault_aad(&user_pubkey, params, &salt);
    let unbound = UnboundKey::new(&CHACHA20_POLY1305, &key)
        .map_err(|_| anyhow!("invalid recovery vault encryption key length"))?;
    let aead_key = LessSafeKey::new(unbound);

    let mut seed = Zeroizing::new(user_sk.to_bytes());
    let mut buf = Zeroizing::new(Vec::with_capacity(32 + AEAD_TAG_LEN));
    buf.extend_from_slice(&*seed);
    seed.zeroize();

    aead_key
        .seal_in_place_append_tag(
            Nonce::assume_unique_for_key(nonce_bytes),
            Aad::from(aad.as_slice()),
            &mut *buf,
        )
        .map_err(|_| anyhow!("recovery vault AEAD encryption failed"))?;

    Ok(RecoveryVaultBlob {
        version: 1,
        kdf_alg: "scrypt".to_string(),
        kdf_params: params,
        salt_b64: STANDARD.encode(salt),
        nonce_b64: STANDARD.encode(nonce_bytes),
        ciphertext_b64: STANDARD.encode(&*buf),
    })
}

/// Decrypts a [`RecoveryVaultBlob`] with `passphrase` and verifies the resulting key matches
/// `expected_user_pubkey`.
pub fn decrypt_recovery_vault(
    vault: &RecoveryVaultBlob,
    expected_user_pubkey: &[u8; 32],
    passphrase: &str,
) -> std::result::Result<SigningKey, VaultDecryptError> {
    if vault.version != 1 {
        return Err(VaultDecryptError::InvalidFormat(format!(
            "unsupported vault version {}",
            vault.version
        )));
    }
    if vault.kdf_alg.trim() != "scrypt" {
        return Err(VaultDecryptError::InvalidFormat(format!(
            "unsupported kdf_alg {:?}",
            vault.kdf_alg
        )));
    }
    validate_scrypt_params(vault.kdf_params).map_err(VaultDecryptError::InvalidFormat)?;

    let salt = decode_base64_flexible(&vault.salt_b64)
        .map_err(|e| VaultDecryptError::InvalidFormat(format!("invalid salt_b64: {e}")))?;
    if !(16..=64).contains(&salt.len()) {
        return Err(VaultDecryptError::InvalidFormat(
            "invalid salt_b64 length (expected 16..=64 bytes)".to_string(),
        ));
    }

    let nonce_vec = decode_base64_flexible(&vault.nonce_b64)
        .map_err(|e| VaultDecryptError::InvalidFormat(format!("invalid nonce_b64: {e}")))?;
    let nonce_bytes: [u8; AEAD_NONCE_LEN] = nonce_vec.try_into().map_err(|_| {
        VaultDecryptError::InvalidFormat("invalid nonce_b64 length (expected 12 bytes)".to_string())
    })?;

    let ciphertext = decode_base64_flexible(&vault.ciphertext_b64)
        .map_err(|e| VaultDecryptError::InvalidFormat(format!("invalid ciphertext_b64: {e}")))?;
    if ciphertext.len() < AEAD_TAG_LEN || ciphertext.len() > MAX_VAULT_CIPHERTEXT_BYTES {
        return Err(VaultDecryptError::InvalidFormat(format!(
            "invalid ciphertext_b64 length (expected {AEAD_TAG_LEN}..={MAX_VAULT_CIPHERTEXT_BYTES} bytes)"
        )));
    }

    if passphrase.is_empty() {
        return Err(VaultDecryptError::WrongPassphrase);
    }

    let key = Zeroizing::new(
        scrypt_rfc7914(
            passphrase.as_bytes(),
            &salt,
            vault.kdf_params.log_n,
            vault.kdf_params.r,
            vault.kdf_params.p,
            32,
        )
        .map_err(|e| VaultDecryptError::InvalidFormat(e.to_string()))?,
    );

    let aad = recovery_vault_aad(expected_user_pubkey, vault.kdf_params, &salt);
    let unbound = UnboundKey::new(&CHACHA20_POLY1305, &key)
        .map_err(|_| VaultDecryptError::InvalidFormat("invalid KDF key length".to_string()))?;
    let aead_key = LessSafeKey::new(unbound);

    let mut buf = Zeroizing::new(ciphertext);
    let plaintext = aead_key
        .open_in_place(
            Nonce::assume_unique_for_key(nonce_bytes),
            Aad::from(aad.as_slice()),
            buf.as_mut_slice(),
        )
        .map_err(|_| VaultDecryptError::WrongPassphrase)?;

    let seed_slice: [u8; 32] = plaintext.try_into().map_err(|_| {
        VaultDecryptError::InvalidFormat(
            "decrypted recovery vault payload is not 32 bytes".to_string(),
        )
    })?;
    let seed = Zeroizing::new(seed_slice);
    buf.zeroize();

    let signing_key = SigningKey::from_bytes(&seed);
    if signing_key.verifying_key().to_bytes() != *expected_user_pubkey {
        return Err(VaultDecryptError::InvalidFormat(
            "decrypted user signing key does not match expected_user_pubkey".to_string(),
        ));
    }

    Ok(signing_key)
}

fn recovery_vault_aad(user_pubkey: &[u8; 32], params: ScryptParams, salt: &[u8]) -> Vec<u8> {
    let mut aad = Vec::with_capacity(DOMAIN_RECOVERY_VAULT_AAD.len() + 32 + 6 + 1 + 4 + 4 + salt.len());
    aad.extend_from_slice(DOMAIN_RECOVERY_VAULT_AAD);
    aad.extend_from_slice(user_pubkey);
    aad.extend_from_slice(b"scrypt");
    aad.push(params.log_n);
    aad.extend_from_slice(&params.r.to_be_bytes());
    aad.extend_from_slice(&params.p.to_be_bytes());
    aad.extend_from_slice(salt);
    aad
}

fn decode_base64_flexible(raw: &str) -> Result<Vec<u8>> {
    let trimmed = raw.trim();
    if let Ok(bytes) = STANDARD.decode(trimmed) {
        return Ok(bytes);
    }
    if let Ok(bytes) = STANDARD_NO_PAD.decode(trimmed) {
        return Ok(bytes);
    }
    if let Ok(bytes) = URL_SAFE.decode(trimmed) {
        return Ok(bytes);
    }
    URL_SAFE_NO_PAD
        .decode(trimmed)
        .context("invalid standard or URL-safe base64")
}

fn decode_base64_fixed<const N: usize>(raw: &str, label: &str) -> Result<[u8; N]> {
    let bytes =
        decode_base64_flexible(raw).with_context(|| format!("invalid base64 in {label}"))?;
    bytes
        .try_into()
        .map_err(|_| anyhow!("{label} must decode to {N} bytes"))
}

fn decode_seed_32(b64: &str, label: &str) -> Result<Zeroizing<[u8; 32]>> {
    let mut vec = URL_SAFE_NO_PAD
        .decode(b64.trim())
        .with_context(|| format!("invalid URL-safe base64 in {label}"))?;
    if vec.len() != 32 {
        vec.zeroize();
        bail!("{label} must decode to 32 bytes");
    }
    let mut seed = Zeroizing::new([0u8; 32]);
    seed.copy_from_slice(&vec);
    vec.zeroize();
    Ok(seed)
}

