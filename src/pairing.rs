    fn test_recovery_vault_roundtrip_and_errors() {
        let user_sk = SigningKey::from_bytes(&[0x66; 32]);
        let user_pk = user_sk.verifying_key().to_bytes();
        let wrong_pk = SigningKey::from_bytes(&[0x77; 32]).verifying_key().to_bytes();
        let passphrase = "correct horse battery staple!";

        // Empty passphrase rejected on encrypt
        assert!(encrypt_recovery_vault(&user_sk, "", ScryptParams { log_n: 10, r: 8, p: 1 }).is_err());

        // Excessive KDF params rejected on encrypt
        assert!(
            encrypt_recovery_vault(&user_sk, passphrase, ScryptParams { log_n: 25, r: 8, p: 1 })
                .is_err()
        );

        // Fast roundtrip (log_n = 10)
        let fast_params = ScryptParams {
            log_n: 10,
            r: 8,
            p: 1,
        };
        let blob = encrypt_recovery_vault(&user_sk, passphrase, fast_params).unwrap();
        let blob_json = serde_json::to_string(&blob).unwrap();
        let blob_parsed: RecoveryVaultBlob = serde_json::from_str(&blob_json).unwrap();

        let recovered = decrypt_recovery_vault(&blob_parsed, &user_pk, passphrase).unwrap();
        assert_eq!(recovered.to_bytes(), user_sk.to_bytes());

        // Wrong passphrase -> WrongPassphrase
        assert!(matches!(
            decrypt_recovery_vault(&blob_parsed, &user_pk, "wrong passphrase"),
            Err(VaultDecryptError::WrongPassphrase)
        ));
        assert!(matches!(
            decrypt_recovery_vault(&blob_parsed, &user_pk, ""),
            Err(VaultDecryptError::WrongPassphrase)
        ));

        // Wrong expected_user_pubkey -> rejected
        assert!(decrypt_recovery_vault(&blob_parsed, &wrong_pk, passphrase).is_err());

        // Excessive KDF params rejected on decrypt
        let mut bad_kdf = blob_parsed.clone();
        bad_kdf.kdf_params.log_n = 25;
        assert!(matches!(
            decrypt_recovery_vault(&bad_kdf, &user_pk, passphrase),
            Err(VaultDecryptError::InvalidFormat(_))
        ));

        // Invalid version / kdf_alg rejected
        let mut bad_ver = blob_parsed.clone();
        bad_ver.version = 2;
        assert!(matches!(
            decrypt_recovery_vault(&bad_ver, &user_pk, passphrase),
            Err(VaultDecryptError::InvalidFormat(_))
        ));
        let mut bad_alg = blob_parsed;
        bad_alg.kdf_alg = "argon2id".to_string();
        assert!(matches!(
            decrypt_recovery_vault(&bad_alg, &user_pk, passphrase),
            Err(VaultDecryptError::InvalidFormat(_))
        ));

        // Default ScryptParams (log_n = 15, r = 8, p = 1) roundtrip
        let default_params = ScryptParams::default();
        assert_eq!(default_params, ScryptParams { log_n: 15, r: 8, p: 1 });
        let default_blob = encrypt_recovery_vault(&user_sk, passphrase, default_params).unwrap();
        let default_recovered = decrypt_recovery_vault(&default_blob, &user_pk, passphrase).unwrap();
        assert_eq!(default_recovered.to_bytes(), user_sk.to_bytes());
    }

